"""Converts host render scripts (host/scripts/*.txt) into a C table for the
board's `render` console command (task 14.1). Same syntax and timing as
host/lxr_render.c, so the Pico plays exactly the events the host plays.

Usage: script_to_c.py out.c script1.txt [script2.txt ...]
"""
import os
import re
import sys

SAMPLE_RATE = 44100
BLOCK = 64


def parse(path):
    events, seconds = [], None
    for no, line in enumerate(open(path), 1):
        m = re.match(r"#\s*seconds:\s*([0-9.]+)", line)
        if m:
            seconds = float(m.group(1))
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        m = re.match(r"t=(\d+)\s+(.*)$", line)
        if not m:
            raise SystemExit(f"{path}:{no}: expected t=<ms>")
        ms, rest = int(m.group(1)), m.group(2).split()
        if events and ms < events[-1][0]:
            raise SystemExit(f"{path}:{no}: times must not decrease")
        if rest[0] == "set":
            events.append((ms, rest[1], int(rest[2]), []))
        else:
            data = [int(b, 16) for b in rest]
            if len(data) > 32 or any(b > 0xFF for b in data):
                raise SystemExit(f"{path}:{no}: bad MIDI bytes")
            events.append((ms, None, 0, data))
    if seconds is None:
        raise SystemExit(f"{path}: missing '# seconds: <n>' line")
    blocks = int(seconds * SAMPLE_RATE / BLOCK + 0.5)   # same rounding as lxr_render.c
    return events, blocks


def main():
    out, scripts = sys.argv[1], sys.argv[2:]
    lines = ["/* Generated by host/scripts/script_to_c.py from host/scripts/*.txt. Do not edit. */",
             '#include "render_scripts.h"', ""]
    table = []
    for path in scripts:
        name = os.path.splitext(os.path.basename(path))[0]
        events, blocks = parse(path)
        ident = re.sub(r"\W", "_", name)
        lines.append(f"static const render_event_t ev_{ident}[] = {{")
        for ms, set_name, value, data in events:
            sn = f'"{set_name}"' if set_name else "NULL"
            bytes_ = "{" + ", ".join(f"0x{b:02X}" for b in data) + "}" if data else "{0}"
            lines.append(f"\t{{ {ms}u, {sn}, {value}u, {len(data)}u, {bytes_} }},")
        lines.append("};")
        table.append(f'\t{{ "{name}", {blocks}u, ev_{ident}, {len(events)}u }},')
    lines.append("")
    lines.append("const render_script_t render_scripts[] = {")
    lines += table
    lines.append("};")
    lines.append(f"const unsigned render_script_count = {len(scripts)}u;")
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
